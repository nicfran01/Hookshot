"""(raiders) The runtime's stand-in for the console's built-in fonts (host/nn_pl_font.c: nn::pl::GetBuiltInFontData):
third_party/fonts/libertinus's regular sans face as a byte array in a C file of the build's own, compiled into the
runtime as nx2/ui_fonts.py does the overlays' fonts for the Vulkan back end. One face, unmodified (SIL Open Font License
1.1: third_party/fonts/PROVENANCE.md).

    python -I nx2/host_font.py [out.c]
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONT = os.path.join(ROOT, "third_party", "fonts", "libertinus", "LibertinusSans-Regular.ttf")
NAME = "hos_builtin_font"   # (host/nn_pl_font.c declares the same names)


def source(path=FONT):
    data = open(path, "rb").read()
    lines = ["/* generated by nx2/host_font.py from third_party/fonts/libertinus/%s (SIL Open Font License 1.1): "
             "do not edit */" % os.path.basename(path),
             "const unsigned %s_size = %d;" % (NAME, len(data)),
             "const unsigned char %s[%d] = {" % (NAME, len(data))]
    for i in range(0, len(data), 48):
        lines.append(",".join(str(b) for b in data[i:i + 48]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def write(out_path, path=FONT):
    """Writes the file when it differs (an unchanged one keeps its timestamp); returns its path"""
    text = source(path)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    try:
        same = open(out_path, encoding="utf-8").read() == text
    except OSError:
        same = False
    if not same:
        with open(out_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return out_path


if __name__ == "__main__":
    write(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "host_font.c"))
